// Baseline traffic
// ---------------------------------------------------------------------------

/**
 * Generates a principal's ordinary activity across the whole window.
 *
 * Walks every hour of every day and asks {@link activityMultiplier} how busy
 * this principal is, then draws that many events at random moments inside the
 * hour.
 *
 * @param profile - the principal to generate for.
 * @param random - a generator dedicated to this principal.
 * @param startTime - first instant of the window.
 * @param days - length of the window.
 * @returns the principal's events, in no particular order — the caller sorts.
 */
function generateBaseline(
  profile: PrincipalProfile,
  random: Random,
  startTime: Date,
  days: number,
): CloudTrailEvent[] {
  const events: CloudTrailEvent[] = [];
  const totalHours = days * 24;

  for (let hour = 0; hour < totalHours; hour += 1) {
    const hourStart = new Date(startTime.getTime() + hour * HOUR_MS);
    const multiplier = activityMultiplier(profile, hourStart, random);

    if (multiplier <= 0) continue;

    const count = Math.max(
      0,
      Math.round(
        random.normal(
          profile.eventsPerHourMean * multiplier,
          profile.eventsPerHourStdDev,
        ),
      ),
    );

    for (let index = 0; index < count; index += 1) {
      // Uniform within the hour. Real calls arrive in bursts, but bursts inside
      // a one-hour bucket are invisible to hourly features, so modelling them
      // would add generator complexity that no downstream feature can see.
      const offsetMs = random.int(0, HOUR_MS - 1);
      events.push(
        buildEvent(profile, random, new Date(hourStart.getTime() + offsetMs)),
      );
    }
  }

  return events;
}

