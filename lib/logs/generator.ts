/**
 * CloudSentinel — synthetic CloudTrail activity generator.
 *
 * Produces a realistic stream of AWS API-call records for a fictional account,
 * plus a separate answer key describing the attacks deliberately hidden inside
 * it. This is the data source for the ML anomaly layer.
 *
 *   npm run logs:gen                       write the default 30-day log
 *   npm run logs:gen -- --days 7           a shorter log
 *   npm run logs:gen -- --seed other       a different (still reproducible) run
 *   npm run logs:gen -- --no-attacks       clean baseline traffic only
 *
 * Where it sits in the architecture: the head of stage three. Everything it
 * emits conforms to lib/types/cloudtrail.ts, which is the contract the Python
 * layer parses against.
 *
 *   [ this file ] --> fixtures/cloudtrail.json ------> ml/features.py --> ml/detect.py
 *                 \                                                          |
 *                  -> fixtures/cloudtrail-labels.json --> ml/evaluate.py <---+
 *
 * ---------------------------------------------------------------------------
 * Why synthesize the data at all
 * ---------------------------------------------------------------------------
 *
 * The honest answer is that there is no alternative that is both legal and
 * useful. Real CloudTrail logs are among the most sensitive artefacts an AWS
 * account produces — they record who did what, from which address, at what
 * hour — so no organisation publishes them, and none should. The public
 * intrusion-detection datasets that do exist are network traces, not
 * cloud-control-plane traces, and LocalStack does not emit a usable trail.
 *
 * Synthetic data buys something a real trail could not, though, and it is worth
 * being clear about it: **ground truth**. In a real log nobody knows with
 * certainty which events were an attack, so "the model flagged 4 things" is
 * unfalsifiable. Here the attacks are placed on purpose, so precision and
 * recall are actually computable and a claim like "the Isolation Forest beat
 * the statistical baseline" can be checked rather than asserted.
 *
 * The cost, which must not be glossed over: a model evaluated only on data
 * generated by these rules is partly being tested on the generator's
 * assumptions. If the generator believes analysts never work at night, the
 * detector will look excellent at spotting night-time analysts and will say
 * nothing about how it behaves in an account where half the team is in Berlin.
 * The numbers in ml/evaluate.py are therefore a demonstration that the pipeline
 * works end to end, not a claim about real-world accuracy. That distinction is
 * repeated in the evaluation output itself so nobody quotes the figure without
 * the caveat.
 *
 * ---------------------------------------------------------------------------
 * The control group
 * ---------------------------------------------------------------------------
 *
 * Two principals below exist to be *boring in a difficult way*, mirroring the
 * compliant buckets that scripts/seed-localstack.ts uses as a false-positive
 * baseline for the rule engine:
 *
 *   - `backup-service` is an automated role running 24/7 with a large nightly
 *     batch spike. It is active at 3am and it makes hundreds of calls an hour.
 *     A naive detector keyed on "night-time activity" or "high volume" flags it
 *     every single day.
 *   - `dave-admin` performs IAM writes — `AttachUserPolicy`, `CreateAccessKey`
 *     — as his ordinary job. A detector keyed on "sensitive IAM action" flags
 *     him constantly.
 *
 * Both must come out clean. That is the entire argument for baselining
 * per-principal rather than account-wide: the *same* action is unremarkable
 * from Dave and alarming from an analyst who has never called IAM in his life.
 * A model that cannot express that is a model that either misses the real
 * escalation or drowns the account in false positives, and either failure gets
 * the tool switched off.
 *
 * SECURITY: everything here is fabricated. The account id is the reserved
 * documentation placeholder, and every address comes from the RFC 5737 example
 * ranges (192.0.2.0/24, 198.51.100.0/24, 203.0.113.0/24), which route nowhere.
 * That is deliberate for a public repository: a plausible-looking invented IP
 * usually belongs to somebody real, and committing a file that appears to
 * accuse a genuine address of credential theft is a concrete harm even when the
 * surrounding data is fake. The names are equally fictional and match the
 * `cloudsentinel-*` fixtures used elsewhere in the project.
 */

