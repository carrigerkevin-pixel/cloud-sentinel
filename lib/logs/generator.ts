/**
 * The behavioural fingerprint of one principal.
 *
 * Everything the generator needs to produce a month of plausible activity for
 * one identity: when it works, where it works from, how much it does, and what
 * kinds of calls it makes.
 *
 * The fields describing *when* are the ones that carry the most weight. Real
 * principals fall into two sharply different populations — humans, who work a
 * local business day and rest at night, and automation, which runs on a
 * schedule and does not care what time it is. Modelling both is necessary
 * because a detector that assumes everything is human flags every backup job,
 * and one that assumes everything is automated notices nothing at all.
 */
export interface PrincipalProfile {
  /** Full ARN — the grouping key for every downstream feature. */
  arn: string;

  /** AWS's opaque principal id, e.g. `AIDA...`. */
  principalId: string;

  /** Which identity variant this is. See lib/types/cloudtrail.ts. */
  type: "IAMUser" | "AssumedRole" | "Root";

  /** IAM user name, for `IAMUser` principals. */
  userName?: string;

  /** Role session name, for `AssumedRole` principals. */
  sessionName?: string;

  /** Plain-language note on the persona, shown in generator output. */
  description: string;

  /**
   * Offset from UTC of the principal's local time, in hours.
   *
   * Stored as an offset rather than a timezone name so that no timezone
   * database is needed and the arithmetic is one addition. Daylight saving is
   * deliberately not modelled: it would shift the working-hours boundary
   * mid-month and make the off-hours feature noisier for reasons that have
   * nothing to do with security. A real deployment would have to handle it.
   */
  utcOffsetHours: number;

  /** First hour of the working day, in the principal's local time (0-23). */
  workStartHourLocal: number;

  /** Last hour of the working day, in local time, inclusive. */
  workEndHourLocal: number;

  /** Whether this principal is normally active on Saturdays and Sundays. */
  worksWeekends: boolean;

  /**
   * Whether this principal ignores working hours entirely.
   *
   * `true` for automation. An always-on principal is active every hour of every
   * day, which means the off-hours feature must produce *nothing* for it —
   * see {@link offHoursFraction}.
   */
  alwaysOn: boolean;

  /**
   * Hour (UTC) at which an always-on principal runs a heavier batch, or `null`.
   *
   * This exists specifically to be a trap for the volume feature. The backup
   * role does six times its usual work at 02:00 UTC every night, so a detector
   * that flags volume spikes without accounting for recurrence reports the same
   * "anomaly" thirty times in thirty days.
   */
  batchHourUtc: number | null;

  /** The region this principal normally calls from. */
  homeRegion: string;

  /**
   * The first three octets of the principal's usual source address.
   *
   * A /24 rather than a single address because real people move between an
   * office, a VPN and a home connection without that being suspicious. The
   * new-geo signal is a call from a *different* prefix entirely.
   */
  homeIpPrefix: string;

  /** User agent strings this principal's tooling reports. */
  userAgents: string[];

  /** Mean number of events in an active hour. */
  eventsPerHourMean: number;

  /** Standard deviation of that count, giving each hour natural variance. */
  eventsPerHourStdDev: number;

  /**
   * Fraction of calls that fail with `AccessDenied` in normal operation.
   *
   * Non-zero on purpose. A baseline of exactly zero errors would make the
   * credential-abuse scenario trivially detectable by a single `if` statement,
   * which would flatter the model. Real accounts always have a low background
   * rate of permission errors from misconfigured tooling and stale scripts.
   */
  errorRate: number;

  /** The weighted action vocabulary this principal draws from. */
  actions: WeightedAction[];
}

