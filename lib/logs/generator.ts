/** Options for {@link generateActivity}. All have defaults. */
export interface GenerateOptions {
  /** PRNG seed. The same seed always produces byte-identical output. */
  seed?: string;

  /** Length of the generated window in days. Must be at least 1. */
  days?: number;

  /** ISO 8601 UTC timestamp for the start of the window. */
  startTime?: string;

  /** Principals to generate for. Defaults to {@link DEFAULT_PRINCIPALS}. */
  principals?: PrincipalProfile[];

  /**
   * Whether to inject the labelled attacks.
   *
   * `false` produces clean baseline traffic with an empty label set. That mode
   * exists to answer a question the attack-laden log cannot: how many
   * *false* positives does the detector produce on a month of ordinary work?
   * A model can score well on recall and still be unusable if it flags the
   * backup job every night, and only a clean run measures that.
   */
  injectAttacks?: boolean;
}

/** What {@link generateActivity} returns: the log and its separate answer key. */
export interface GeneratedActivity {
  /** The events, with no labels. This is all the detector ever sees. */
  log: ActivityLog;

  /** The answer key, read only by the evaluation step. */
  labels: ActivityLabels;
}

/**
 * Generates a full synthetic activity log with labelled attacks hidden in it.
 *
 * Each principal is given its own generator, seeded from the run seed plus its
 * ARN. That is a deliberate structural choice: it means adding, removing or
 * reordering a principal changes only that principal's events, leaving everyone
 * else's stream untouched. With one shared generator, inserting a principal
 * would shift every subsequent draw and rewrite the entire log — making any
 * change to the roster produce an unreviewable diff and invalidating any
 * threshold tuned against the previous data.
 *
 * The attacks are scheduled in the second half of the window so that each
 * victim has weeks of established normal behaviour behind it. That ordering is
 * not cosmetic: the detector baselines a principal against its own history, so
 * an attack on day 2 would be measured against almost no history and would be
 * unfairly hard to catch.
 *
 * @param options - see {@link GenerateOptions}.
 * @returns the log and the labels, both sorted by time.
 * @throws {RangeError} if `days` is less than 1, if `startTime` is not a valid
 *   date, or if `principals` is empty — each of which would otherwise produce a
 *   silently empty log that looks like a detector failure much later.
 */
export function generateActivity(
  options: GenerateOptions = {},
): GeneratedActivity {
  const seed = options.seed ?? DEFAULT_SEED;
  const days = options.days ?? DEFAULT_DAYS;
  const principals = options.principals ?? DEFAULT_PRINCIPALS;
  const injectAttacks = options.injectAttacks ?? true;

  if (days < 1) {
    throw new RangeError(`generateActivity: days must be >= 1, got ${days}`);
  }
  if (principals.length === 0) {
    throw new RangeError("generateActivity: at least one principal is required");
  }

  const startTime = new Date(options.startTime ?? DEFAULT_START_TIME);
  if (Number.isNaN(startTime.getTime())) {
    throw new RangeError(
      `generateActivity: startTime is not a valid date: ${options.startTime}`,
    );
  }

  const events: CloudTrailEvent[] = [];
  const labels: AnomalyLabel[] = [];

  // --- Baseline ----------------------------------------------------------

  const generators = new Map<string, Random>();

  for (const profile of principals) {
    const random = createRandom(`${seed}:${profile.arn}`);
    generators.set(profile.arn, random);
    events.push(...generateBaseline(profile, random, startTime, days));
  }

  // --- Attacks -----------------------------------------------------------

  if (injectAttacks) {
    /**
     * Places an attack at a given day and UTC hour of the window.
     *
     * Scheduled by fraction of the window rather than an absolute day so that
     * `--days 7` and `--days 30` both produce a sensible spread with all five
     * scenarios present, instead of silently dropping the later ones off the
     * end of a short run.
     */
    const at = (fraction: number, utcHour: number, minute: number): Date => {
      const day = Math.min(days - 1, Math.floor(days * fraction));
      return new Date(
        startTime.getTime() + day * DAY_MS + utcHour * HOUR_MS + minute * 60_000,
      );
    };

    const byName = (name: string): PrincipalProfile => {
      const found = principals.find((profile) => profile.arn.endsWith(name));
      if (!found) {
        throw new RangeError(
          `generateActivity: no principal matching ${name}; a custom principal list must still include the attack victims, or pass injectAttacks: false`,
        );
      }
      return found;
    };

    const alice = byName("alice-analyst");
    const bob = byName("bob-devops");
    const carol = byName("carol-finance");

    const scheduled: InjectedAttack[] = [
      // 14:10 UTC = mid-morning for Carol. During her working hours on purpose:
      // the error burst has to carry this one on its own.
      injectCredentialAbuse(carol, generators.get(carol.arn)!, at(0.4, 14, 10)),
      // 03:20 UTC = 22:20 the previous evening for Alice.
      injectPrivilegeEscalation(
        alice,
        generators.get(alice.arn)!,
        at(0.5, 3, 20),
      ),
      // 02:00 UTC = 18:00 Pacific — evening for Bob, so the hour is unremarkable
      // and the geography is the signal.
      injectNewGeoLogin(bob, generators.get(bob.arn)!, at(0.6, 2, 0)),
      // 05:30 UTC = 00:30 for Carol. Nothing but the clock is wrong.
      injectOffHoursAccess(carol, generators.get(carol.arn)!, at(0.7, 5, 30)),
      // 16:00 UTC = 11:00 for Alice, squarely inside her working day.
      injectDataExfiltration(alice, generators.get(alice.arn)!, at(0.8, 16, 0)),
    ];

    for (const attack of scheduled) {
      events.push(...attack.events);
      labels.push(attack.label);
    }
  }

  // --- Assembly ----------------------------------------------------------

  // Sorted by time, with the event id as a tie-break. The tie-break matters:
  // two events in the same millisecond would otherwise order differently
  // between Node versions, and a fixture that reshuffles on regeneration cannot
  // be diffed.
  events.sort((a, b) =>
    a.eventTime === b.eventTime
      ? a.eventID.localeCompare(b.eventID)
      : a.eventTime.localeCompare(b.eventTime),
  );

  labels.sort((a, b) => a.startTime.localeCompare(b.startTime));

  const metadata: ActivityLogMetadata = {
    seed,
    startTime: startTime.toISOString(),
    days,
    eventCount: events.length,
    principalCount: principals.length,
    // Derived from the window, not from the clock — see the field's doc comment
    // in lib/types/cloudtrail.ts for why a real timestamp here would break the
    // determinism check.
    generatedAt: new Date(startTime.getTime() + days * DAY_MS).toISOString(),
  };

  return {
    log: { metadata, events },
    labels: { metadata, labels },
  };
}
