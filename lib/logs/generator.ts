/**
 * One kind of API call a principal might make, with how often it makes it.
 *
 * Actions are drawn by weight rather than uniformly, because real activity is
 * heavily skewed: a principal that reads objects makes far more `GetObject`
 * calls than `ListBuckets` calls. Uniform selection would give every principal
 * an unnaturally flat action distribution, and the "distinct actions this hour"
 * feature would then carry no information — every hour would look the same.
 */
interface WeightedAction {
  /** Relative likelihood. Weights need not sum to anything in particular. */
  weight: number;

  /** The service endpoint, e.g. `"s3.amazonaws.com"`. */
  eventSource: string;

  /** The API action name, e.g. `"GetObject"`. */
  eventName: string;

  /** Whether the call only reads state. Drives the write/read ratio feature. */
  readOnly: boolean;

  /** `"Data"` for object-level calls, `"Management"` for control-plane calls. */
  eventCategory: "Management" | "Data";

  /**
   * Builds the recorded request parameters for one call.
   *
   * A function rather than a fixed object so each call can vary — different
   * object keys, different instance ids — which is what makes the
   * "distinct resources touched" signal in the exfiltration scenario possible.
   *
   * @param random - the principal's generator. Drawing from it here advances
   *   the same stream the rest of the principal's events use, which is fine and
   *   deterministic, but means reordering these calls changes the output.
   * @returns the parameters, or `null` for actions that take none.
   */
  parameters?: (random: Random) => Record<string, string | number | boolean>;
}

