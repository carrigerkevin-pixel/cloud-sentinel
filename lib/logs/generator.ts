/**
 * Fields a scenario may override when building an event.
 *
 * The attack generators below produce events that are structurally identical to
 * normal traffic and differ only in these dimensions — which is precisely the
 * situation a real detector faces. An attack event that carried some special
 * marker would make the whole exercise circular.
 */
interface EventOverrides {
  eventSource?: string;
  eventName?: string;
  readOnly?: boolean;
  eventCategory?: "Management" | "Data";
  awsRegion?: string;
  sourceIPAddress?: string;
  userAgent?: string;
  errorCode?: string;
  requestParameters?: Record<string, string | number | boolean> | null;
}

/**
 * Builds one event for a principal at a given instant.
 *
 * @param profile - whose event this is.
 * @param random - the principal's generator.
 * @param timestamp - exact event time.
 * @param overrides - scenario-specific field replacements. Anything omitted is
 *   drawn from the principal's normal profile.
 * @returns a complete {@link CloudTrailEvent}.
 */
function buildEvent(
  profile: PrincipalProfile,
  random: Random,
  timestamp: Date,
  overrides: EventOverrides = {},
): CloudTrailEvent {
  const action = pickWeighted(random, profile.actions);

  const failed =
    overrides.errorCode !== undefined || random.bool(profile.errorRate);

  const event: CloudTrailEvent = {
    eventVersion: EVENT_VERSION,
    eventID: uuid(random),
    eventTime: timestamp.toISOString(),
    eventSource: overrides.eventSource ?? action.eventSource,
    eventName: overrides.eventName ?? action.eventName,
    awsRegion: overrides.awsRegion ?? profile.homeRegion,
    sourceIPAddress:
      overrides.sourceIPAddress ??
      `${profile.homeIpPrefix}.${random.int(1, 254)}`,
    userAgent: overrides.userAgent ?? random.pick(profile.userAgents),
    readOnly: overrides.readOnly ?? action.readOnly,
    eventCategory: overrides.eventCategory ?? action.eventCategory,
    userIdentity: {
      type: profile.type,
      principalId: profile.principalId,
      arn: profile.arn,
      accountId: ACCOUNT_ID,
      ...(profile.userName ? { userName: profile.userName } : {}),
      ...(profile.sessionName ? { sessionName: profile.sessionName } : {}),
    },
    requestParameters:
      overrides.requestParameters !== undefined
        ? overrides.requestParameters
        : (action.parameters?.(random) ?? null),
  };

  if (failed) {
    event.errorCode = overrides.errorCode ?? "AccessDenied";
    event.errorMessage = `User: ${profile.arn} is not authorized to perform: ${event.eventSource.split(".")[0]}:${event.eventName}`;
  }

  return event;
}

