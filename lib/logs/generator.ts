/**
 * One injected attack: the events it produced and the label describing it.
 */
interface InjectedAttack {
  events: CloudTrailEvent[];
  label: AnomalyLabel;
}

/**
 * Builds the label for a set of attack events.
 *
 * Factored out because every scenario needs the same start/end/id bookkeeping,
 * and getting it subtly wrong in one scenario would quietly corrupt the
 * evaluation for that scenario only — the hardest kind of bug to notice in a
 * metrics table.
 *
 * @param scenario - which technique was injected.
 * @param profile - the principal it was performed as.
 * @param events - the attack's events. Must not be empty.
 * @param description - a one-line human-readable summary.
 * @returns the completed label.
 * @throws {RangeError} if `events` is empty, which would mean a scenario
 *   silently generated nothing and would show up as an unexplained recall miss.
 */
function labelFor(
  scenario: AnomalyLabel["scenario"],
  profile: PrincipalProfile,
  events: CloudTrailEvent[],
  description: string,
): AnomalyLabel {
  if (events.length === 0) {
    throw new RangeError(`labelFor: scenario ${scenario} produced no events`);
  }

  const times = events.map((event) => event.eventTime).sort();

  return {
    scenario,
    principalArn: profile.arn,
    startTime: times[0]!,
    endTime: times[times.length - 1]!,
    eventIds: events.map((event) => event.eventID),
    description,
  };
}

/**
 * Privilege escalation: a principal with no IAM history starts rewriting its
 * own permissions.
 *
 * The sequence is the recognisable one — look at yourself, look at your
 * policies, then grant yourself more and mint a key to keep the access. Placed
 * outside working hours, but the hour is *not* the intended signal: the signal
 * is that `alice-analyst` has made zero IAM calls in the preceding weeks and
 * then makes nine in eleven minutes.
 *
 * @param profile - the victim principal.
 * @param random - the principal's generator.
 * @param at - when the sequence begins.
 * @returns the injected events and their label.
 */
function injectPrivilegeEscalation(
  profile: PrincipalProfile,
  random: Random,
  at: Date,
): InjectedAttack {
  const sequence: Array<[string, string, boolean, Record<string, string>]> = [
    ["sts.amazonaws.com", "GetCallerIdentity", true, {}],
    ["iam.amazonaws.com", "GetUser", true, { userName: "alice-analyst" }],
    [
      "iam.amazonaws.com",
      "ListAttachedUserPolicies",
      true,
      { userName: "alice-analyst" },
    ],
    ["iam.amazonaws.com", "ListUserPolicies", true, { userName: "alice-analyst" }],
    [
      "iam.amazonaws.com",
      "CreatePolicyVersion",
      false,
      {
        policyArn: `arn:aws:iam::${ACCOUNT_ID}:policy/analyst-readonly`,
        setAsDefault: "true",
      },
    ],
    [
      "iam.amazonaws.com",
      "AttachUserPolicy",
      false,
      {
        userName: "alice-analyst",
        policyArn: "arn:aws:iam::aws:policy/AdministratorAccess",
      },
    ],
    [
      "iam.amazonaws.com",
      "PutUserPolicy",
      false,
      { userName: "alice-analyst", policyName: "inline-escalation" },
    ],
    ["iam.amazonaws.com", "CreateAccessKey", false, { userName: "alice-analyst" }],
    ["iam.amazonaws.com", "ListUsers", true, {}],
  ];

  // A single stolen session: one address for the whole sequence.
  const sourceIp = `${profile.homeIpPrefix}.${random.int(1, 254)}`;
  let cursor = at.getTime();
  const events: CloudTrailEvent[] = [];

  for (const [eventSource, eventName, readOnly, parameters] of sequence) {
    events.push(
      buildEvent(profile, random, new Date(cursor), {
        eventSource,
        eventName,
        readOnly,
        eventCategory: "Management",
        sourceIPAddress: sourceIp,
        requestParameters: Object.keys(parameters).length > 0 ? parameters : null,
      }),
    );
    // Tens of seconds apart: fast enough to be one session, slow enough to look
    // like a person typing rather than a script.
    cursor += random.int(20_000, 110_000);
  }

  return {
    events,
    label: labelFor(
      "privilege_escalation",
      profile,
      events,
      `${events.length} IAM calls in ${Math.round((cursor - at.getTime()) / 60_000)} minutes by a principal with no prior IAM activity, ending in AttachUserPolicy(AdministratorAccess) and CreateAccessKey`,
    ),
  };
}

/**
 * Off-hours access: entirely ordinary work, done in the middle of the night.
 *
 * Deliberately the weakest scenario in the set. Every event uses the
 * principal's normal actions, normal address and normal region; the only thing
 * wrong is the clock. It is included to test whether the model can act on a
 * single weak feature, and it is genuinely acceptable for a detector to rank
 * this lowest — that result is reported honestly by ml/evaluate.py rather than
 * tuned away.
 *
 * @param profile - the principal.
 * @param random - the principal's generator.
 * @param at - when the session begins, in UTC.
 * @returns the injected events and their label.
 */
function injectOffHoursAccess(
  profile: PrincipalProfile,
  random: Random,
  at: Date,
): InjectedAttack {
  const events: CloudTrailEvent[] = [];
  const durationMinutes = random.int(70, 110);
  const count = random.int(26, 38);

  for (let index = 0; index < count; index += 1) {
    const offsetMs = random.int(0, durationMinutes * 60_000);
    events.push(buildEvent(profile, random, new Date(at.getTime() + offsetMs)));
  }

  const localHour = toLocalHour(at.getUTCHours(), profile.utcOffsetHours);

  return {
    events,
    label: labelFor(
      "off_hours_access",
      profile,
      events,
      `${count} routine calls beginning at ${String(localHour).padStart(2, "0")}:00 local time, well outside this principal's ${profile.workStartHourLocal}:00-${profile.workEndHourLocal}:00 pattern`,
    ),
  };
}

/**
 * New-geo login: a console sign-in from a region and address range this
 * principal has never used, followed by exploratory calls.
 *
 * The classic "impossible travel" alert. Two features move at once here — an
 * unseen region and an unseen IP prefix — which makes it the scenario a
 * detector is most likely to catch, and a useful upper bound on what the
 * pipeline can do.
 *
 * @param profile - the principal.
 * @param random - the principal's generator.
 * @param at - when the login happens.
 * @returns the injected events and their label.
 */
function injectNewGeoLogin(
  profile: PrincipalProfile,
  random: Random,
  at: Date,
): InjectedAttack {
  // A prefix and region the profile never uses. Hard-coded rather than derived
  // so the scenario cannot accidentally pick the principal's own home range if
  // the profiles are later edited.
  const foreignIp = `203.0.113.${random.int(1, 254)}`;
  const foreignRegion = "eu-west-1";

  const events: CloudTrailEvent[] = [
    buildEvent(profile, random, at, {
      eventSource: "signin.amazonaws.com",
      eventName: "ConsoleLogin",
      readOnly: false,
      eventCategory: "Management",
      awsRegion: foreignRegion,
      sourceIPAddress: foreignIp,
      userAgent: "Mozilla/5.0 (X11; Linux x86_64) AWS-Console",
      requestParameters: { mfaUsed: "No" },
    }),
  ];

  let cursor = at.getTime() + random.int(30_000, 90_000);
  const followUpCount = random.int(14, 20);

  for (let index = 0; index < followUpCount; index += 1) {
    events.push(
      buildEvent(profile, random, new Date(cursor), {
        awsRegion: foreignRegion,
        sourceIPAddress: foreignIp,
        userAgent: "Mozilla/5.0 (X11; Linux x86_64) AWS-Console",
      }),
    );
    cursor += random.int(15_000, 70_000);
  }

  return {
    events,
    label: labelFor(
      "new_geo_login",
      profile,
      events,
      `ConsoleLogin without MFA from ${foreignIp} in ${foreignRegion}, a region and address range never previously used by this principal, followed by ${followUpCount} calls`,
    ),
  };
}

/**
 * Credential abuse: someone finding out what a stolen key can reach.
 *
 * A burst of calls across services the principal never touches, most of which
 * fail with `AccessDenied`. This is what permission enumeration looks like from
 * the log's side, and the error rate is the signal — an attacker with a stolen
 * credential does not know its scope, so they discover it by trying, whereas a
 * legitimate user's tooling was built around permissions they already have.
 *
 * @param profile - the principal whose credential was abused.
 * @param random - the principal's generator.
 * @param at - when the burst begins.
 * @returns the injected events and their label.
 */
function injectCredentialAbuse(
  profile: PrincipalProfile,
  random: Random,
  at: Date,
): InjectedAttack {
  const probes: Array<[string, string]> = [
    ["iam.amazonaws.com", "ListUsers"],
    ["iam.amazonaws.com", "ListRoles"],
    ["iam.amazonaws.com", "ListAccessKeys"],
    ["iam.amazonaws.com", "GetAccountSummary"],
    ["iam.amazonaws.com", "ListAttachedUserPolicies"],
    ["ec2.amazonaws.com", "DescribeInstances"],
    ["ec2.amazonaws.com", "DescribeSecurityGroups"],
    ["ec2.amazonaws.com", "DescribeVpcs"],
    ["s3.amazonaws.com", "ListBuckets"],
    ["s3.amazonaws.com", "GetBucketPolicy"],
    ["kms.amazonaws.com", "ListKeys"],
    ["lambda.amazonaws.com", "ListFunctions"],
    ["rds.amazonaws.com", "DescribeDBInstances"],
    ["secretsmanager.amazonaws.com", "ListSecrets"],
    ["dynamodb.amazonaws.com", "ListTables"],
    ["sts.amazonaws.com", "GetCallerIdentity"],
  ];

  const sourceIp = `203.0.113.${random.int(1, 254)}`;
  const count = random.int(28, 40);
  let cursor = at.getTime();
  const events: CloudTrailEvent[] = [];
  let denied = 0;

  for (let index = 0; index < count; index += 1) {
    const [eventSource, eventName] = random.pick(probes);
    // Most probes fail — that is the whole point of probing. `GetCallerIdentity`
    // is the exception every credential can call, which is why it is usually
    // the attacker's first move.
    const fails = eventName !== "GetCallerIdentity" && random.bool(0.82);
    if (fails) denied += 1;

    events.push(
      buildEvent(profile, random, new Date(cursor), {
        eventSource,
        eventName,
        readOnly: true,
        eventCategory: "Management",
        sourceIPAddress: sourceIp,
        requestParameters: null,
        ...(fails ? { errorCode: "AccessDenied" } : {}),
      }),
    );

    // Scripted, so much faster than a human clicking around.
    cursor += random.int(1_500, 12_000);
  }

  return {
    events,
    label: labelFor(
      "credential_abuse",
      profile,
      events,
      `${count} enumeration calls across ${new Set(probes.map(([source]) => source)).size} services from ${sourceIp}, ${denied} of them denied — permission discovery with a stolen credential`,
    ),
  };
}

/**
 * Data exfiltration: a read-volume spike far beyond the principal's baseline.
 *
 * Runs during working hours, from the principal's usual address, using an
 * action the principal calls all day. Nothing about any individual event is
 * suspicious; only the rate and the breadth of objects touched are. This is the
 * scenario that most clearly justifies per-principal baselining — 300
 * `GetObject` calls in half an hour is a crisis for an analyst and a quiet
 * afternoon for a backup job.
 *
 * @param profile - the principal.
 * @param random - the principal's generator.
 * @param at - when the spike begins.
 * @returns the injected events and their label.
 */
function injectDataExfiltration(
  profile: PrincipalProfile,
  random: Random,
  at: Date,
): InjectedAttack {
  const events: CloudTrailEvent[] = [];
  const count = random.int(260, 340);
  const durationMs = random.int(20, 32) * 60_000;
  const sourceIp = `${profile.homeIpPrefix}.${random.int(1, 254)}`;

  for (let index = 0; index < count; index += 1) {
    events.push(
      buildEvent(profile, random, new Date(at.getTime() + random.int(0, durationMs)), {
        eventSource: "s3.amazonaws.com",
        eventName: "GetObject",
        readOnly: true,
        eventCategory: "Data",
        sourceIPAddress: sourceIp,
        userAgent: "aws-cli/2.36.29 Python/3.12.4 Darwin/24.1.0",
        requestParameters: {
          bucketName: "cloudsentinel-analytics",
          // A distinct key every time: this is a sweep of the bucket, not a
          // retry loop, and the distinct-resource count is what separates them.
          key: `datasets/${random.int(2019, 2026)}/part-${index}-${random.int(1000, 9999)}.parquet`,
        },
      }),
    );
  }

  return {
    events,
    label: labelFor(
      "data_exfiltration",
      profile,
      events,
      `${count} GetObject calls in ${Math.round(durationMs / 60_000)} minutes against ${count} distinct keys, roughly ${Math.round(count / (durationMs / HOUR_MS) / profile.eventsPerHourMean)}x this principal's normal hourly rate`,
    ),
  };
}

