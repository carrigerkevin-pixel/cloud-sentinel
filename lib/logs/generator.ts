/**
 * Builds a v4-shaped UUID from the seeded generator.
 *
 * `node:crypto`'s `randomUUID()` is not usable here: it draws from the system
 * entropy pool, so it would produce a different id on every run and destroy the
 * reproducibility the whole layer depends on. The version and variant nibbles
 * are set so the result is a well-formed v4 UUID, which matters only because a
 * malformed id in a fixture is the kind of thing that wastes an afternoon
 * later.
 *
 * SECURITY: predictable by construction, as with everything in
 * lib/util/random.ts. Never use this to mint an identifier that anything trusts.
 *
 * @param random - the generator to draw 16 bytes from.
 * @returns a lowercase, hyphenated UUID string.
 */
function uuid(random: Random): string {
  const bytes = Array.from({ length: 16 }, () => random.int(0, 255));

  // Version 4 in the high nibble of byte 6, RFC 4122 variant in byte 8.
  bytes[6] = (bytes[6]! & 0x0f) | 0x40;
  bytes[8] = (bytes[8]! & 0x3f) | 0x80;

  const hex = bytes.map((b) => b.toString(16).padStart(2, "0")).join("");

  return [
    hex.slice(0, 8),
    hex.slice(8, 12),
    hex.slice(12, 16),
    hex.slice(16, 20),
    hex.slice(20),
  ].join("-");
}

/**
 * Picks an action from a weighted list.
 *
 * Linear scan over the cumulative weight. With at most a dozen actions per
 * principal there is nothing to gain from a binary search, and the obvious
 * version is the one that can be checked by eye.
 *
 * @param random - the principal's generator.
 * @param actions - must not be empty.
 * @returns the selected action.
 * @throws {RangeError} if `actions` is empty, matching `Random.pick`.
 */
function pickWeighted(random: Random, actions: WeightedAction[]): WeightedAction {
  if (actions.length === 0) {
    throw new RangeError("pickWeighted: cannot pick from an empty action list");
  }

  const total = actions.reduce((sum, action) => sum + action.weight, 0);
  let threshold = random.next() * total;

  for (const action of actions) {
    threshold -= action.weight;
    if (threshold <= 0) return action;
  }

  // Floating-point rounding can leave a hair above zero on the last subtraction.
  return actions[actions.length - 1]!;
}

/**
 * Converts a UTC hour to the principal's local hour.
 *
 * @param utcHour - hour of day in UTC, 0-23.
 * @param offsetHours - the principal's offset from UTC.
 * @returns the local hour, wrapped into 0-23.
 */
function toLocalHour(utcHour: number, offsetHours: number): number {
  return ((utcHour + offsetHours) % 24 + 24) % 24;
}

/**
 * Decides whether a principal is active in a given hour, and how busy.
 *
 * @param profile - the principal.
 * @param timestamp - the start of the UTC hour under consideration.
 * @param random - the principal's generator.
 * @returns a multiplier on the principal's mean hourly rate. `0` means the
 *   principal produces no events this hour at all.
 */
function activityMultiplier(
  profile: PrincipalProfile,
  timestamp: Date,
  random: Random,
): number {
  const utcHour = timestamp.getUTCHours();

  if (profile.alwaysOn) {
    // Automation runs constantly, with a scheduled heavy window. The batch is a
    // fixed multiplier rather than a random one so it recurs identically every
    // night — a spike that is *predictable* is the thing the detector must
    // learn to ignore.
    return profile.batchHourUtc !== null && utcHour === profile.batchHourUtc
      ? 6
      : 1;
  }

  const dayOfWeek = timestamp.getUTCDay();
  const isWeekend = dayOfWeek === 0 || dayOfWeek === 6;

  if (isWeekend && !profile.worksWeekends) {
    // Not zero. A human who never once touches the console at a weekend is a
    // cleaner signal than reality provides, and a detector tuned against that
    // would over-trust the day-of-week feature. Roughly one weekend hour in
    // twenty-five sees a little activity.
    return random.bool(0.04) ? 0.3 : 0;
  }

  const localHour = toLocalHour(utcHour, profile.utcOffsetHours);
  const withinWorkingHours =
    localHour >= profile.workStartHourLocal &&
    localHour <= profile.workEndHourLocal;

  if (withinWorkingHours) {
    // A midday hump: people are busiest in the middle of their day. Without
    // this the working day is a flat plateau, and the volume feature has less
    // natural variance to distinguish a real spike from.
    const middayDistance = Math.abs(
      localHour - (profile.workStartHourLocal + profile.workEndHourLocal) / 2,
    );
    return 1.25 - middayDistance * 0.06;
  }

  // Outside working hours but on a workday: the occasional late email or early
  // start. Again deliberately non-zero, for the same reason as the weekend case.
  return random.bool(0.07) ? 0.35 : 0;
}

